export default function Referral() {
    const [open, setOpen] = useState(false);
    const user = useQuery(api.user.user);
    const referrals = useQuery(api.referrals.view_referrals) ?? [];
    const { theme } = useTheme();

    const totalReferral = referrals.filter(
        (referral: any) =>
            referral?.referral_code === user?.referral_code,
    );
    const totalReward =
        totalReferral.reduce(
            (sum: number, ref: any) => sum + (ref?.reward_amount ?? 0),
            0,
        ) ?? 0;
    const referralRate =
        totalReferral.length > 0
            ? (totalReward / totalReferral.length) * 100
            : 0;

    const copyToClipboard = async (text?: string) => {
        if (!text) return;

        try {
            await navigator.clipboard.writeText(text);
            toast.success("Copied to clipboard");
        } catch {
            toast.error("Couldn't copy to clipboard");
        }
    };

    const referralLink = `https://verdstampdigital.app/auth/signup?c=${user?.referral_code}`;

    if (!user) {
        return (
            <div className="w-full">
                <PageHero
                    align="center"
                    eyebrow="Referral program"
                    title={
                        <>
                            Invite friends. Earn{" "}
                            <span className="text-lnd-accent">together.</span>
                        </>
                    }
                    subtitle="Invite friends to register and trade to share top-tier referral rewards. Seize this great earning opportunity with your friends!"
                    actions={
                        <>
                            <Link
                                href="/auth/login"
                                className="lnd-btn-accent inline-flex items-center gap-2 px-7 py-3 text-sm"
                            >
                                Log in to participate
                            </Link>
                            <Link
                                href="#how-it-works"
                                className="lnd-btn-ghost inline-flex items-center gap-2 px-6 py-3 text-sm"
                            >
                                How it works
                            </Link>
                        </>
                    }
                    footer={
                        <div className="mx-auto flex max-w-xl items-center justify-center rounded-full border border-lnd-border bg-lnd-surface px-5 py-3">
                            <RewardCarousel />
                        </div>
                    }
                />

                <ReferralSections />

                <PageCta
                    eyebrow="Get started"
                    title="Earn referral rewards now!"
                    description="Create an account, get your exclusive referral link and start earning together with your friends."
                    label="Create account"
                />
            </div>
        );
    }

    return (
        <div className="w-full">
            {/* Signed-in hero */}
            <section className="relative w-full overflow-hidden border-b border-lnd-border">
                <div
                    aria-hidden
                    className="lnd-dot-grid pointer-events-none absolute inset-0 opacity-50 [mask-image:radial-gradient(ellipse_65%_80%_at_50%_0%,black,transparent)]"
                />
                <div
                    aria-hidden
                    className="lnd-glow pointer-events-none absolute -right-48 -top-24 h-[480px] w-[720px] blur-2xl"
                />
                <div className="relative mx-auto w-full max-w-[1280px] px-4 py-14 lg:px-6 lg:py-20">
                    <div className="grid items-center gap-10 lg:grid-cols-[1.1fr_0.9fr] lg:gap-14">
                        <div>
                            <p className="text-[0.66rem] font-semibold uppercase tracking-[0.18em] text-lnd-accent">
                                Referral program
                            </p>
                            <h1 className="mt-3 max-w-2xl font-Manrope text-[2.2rem] font-extrabold leading-[1.08] tracking-tight text-lnd-fg sm:text-5xl lg:text-[3.2rem]">
                                Invite friends. Earn{" "}
                                <span className="text-lnd-accent">
                                    together.
                                </span>
                            </h1>
                            <p className="mt-5 max-w-xl text-base leading-relaxed text-lnd-fg-muted">
                                Share your exclusive link. When your friends
                                register and trade, you both share referral
                                rewards.
                            </p>

                            <div className="mt-7 flex flex-col gap-3 sm:flex-row">
                                <div className="flex min-w-0 flex-1 items-center gap-2 rounded-full border border-lnd-border bg-lnd-surface py-1.5 pl-4 pr-1.5">
                                    <Link2 className="h-4 w-4 shrink-0 text-lnd-fg-muted" />
                                    <span className="truncate text-sm text-lnd-fg-muted">
                                        {referralLink}
                                    </span>
                                    <button
                                        type="button"
                                        onClick={() =>
                                            copyToClipboard(referralLink)
                                        }
                                        className="lnd-btn-accent ml-auto inline-flex shrink-0 items-center gap-1.5 px-4 py-2 text-xs"
                                    >
                                        <Copy className="h-3.5 w-3.5" />
                                        Copy link
                                    </button>
                                </div>

                                <Dialog open={open} onOpenChange={setOpen}>
                                    <DialogTrigger asChild>
                                        <button
                                            type="button"
                                            className="lnd-btn-ghost inline-flex shrink-0 items-center justify-center gap-2 px-5 py-3 text-sm"
                                        >
                                            <QrCode className="h-4 w-4" />
                                            QR code
                                        </button>
                                    </DialogTrigger>
                                    <DialogContent className="border-lnd-border bg-lnd-surface text-lnd-fg sm:max-w-md">
                                        <DialogHeader>
                                            <DialogTitle className="font-Manrope text-xl font-bold text-lnd-fg">
                                                Scan QR code
                                            </DialogTitle>
                                            <DialogDescription className="text-lnd-fg-muted">
                                                Scan this QR code to share
                                                your referral link.
                                            </DialogDescription>
                                        </DialogHeader>
                                        <div className="flex justify-center rounded-xl border border-lnd-border bg-lnd-surface-2 p-4">
                                            <QRCode
                                                value={referralLink}
                                                size={256}
                                                bgColor={
                                                    theme === "dark"
                                                        ? "#121A16"
                                                        : "#FFFFFF"
                                                }
                                                fgColor={
                                                    theme === "dark"
                                                        ? "#A0EA82"
                                                        : "#111814"
                                                }
                                            />
                                        </div>
                                    </DialogContent>
                                </Dialog>
                            </div>

                            <div className="mt-4 flex flex-wrap items-center gap-3">
                                <span className="text-xs text-lnd-fg-muted">
                                    Code:
                                </span>
                                <button
                                    type="button"
                                    onClick={() =>
                                        copyToClipboard(user.referral_code)
                                    }
                                    className="inline-flex items-center gap-1.5 rounded-full border border-lnd-border bg-lnd-surface px-3 py-1.5 font-mono text-xs font-semibold text-lnd-fg transition-colors hover:border-lnd-accent/40"
                                >
                                    {user.referral_code ?? "—"}
                                    <Copy className="h-3 w-3 text-lnd-fg-muted" />
                                </button>
                                <span className="text-xs text-lnd-fg-muted">
                                    Rewards are settled in USDT.
                                </span>
                            </div>

                            <div className="mt-6 inline-flex max-w-full items-center rounded-full border border-lnd-border bg-lnd-surface px-4 py-2">
                                <RewardCarousel />
                            </div>
                        </div>

                        {/* Referral data card */}
                        <div className="relative overflow-hidden rounded-3xl border border-lnd-border bg-lnd-surface p-6 lg:p-8">
                            <div
                                aria-hidden
                                className="lnd-glow pointer-events-none absolute -right-24 -top-24 h-64 w-64"
                            />
                            <div className="relative">
                                <p className="text-[0.66rem] font-semibold uppercase tracking-[0.18em] text-lnd-fg-muted">
                                    Your referral data
                                </p>

                                <div className="mt-5 space-y-4">
                                    <div className="flex items-center justify-between gap-4 border-b border-lnd-border pb-4">
                                        <span className="flex items-center gap-2 text-sm text-lnd-fg-muted">
                                            <Users className="h-4 w-4 text-lnd-accent" />
                                            Total referrals
                                        </span>
                                        <span className="font-Manrope text-xl font-bold text-lnd-fg">
                                            {totalReferral.length}
                                        </span>
                                    </div>
                                    <div className="flex items-center justify-between gap-4 border-b border-lnd-border pb-4">
                                        <span className="flex items-center gap-2 text-sm text-lnd-fg-muted">
                                            <Star className="h-4 w-4 text-lnd-accent" />
                                            Total rewards
                                        </span>
                                        <span className="font-Manrope text-xl font-bold text-lnd-accent">
                                            {totalReward.toLocaleString(
                                                "en-US",
                                                {
                                                    maximumFractionDigits: 2,
                                                },
                                            )}{" "}
                                            <span className="text-xs font-medium">
                                                USD
                                            </span>
                                        </span>
                                    </div>
                                    <div className="flex items-center justify-between gap-4">
                                        <span className="flex items-center gap-2 text-sm text-lnd-fg-muted">
                                            <Award className="h-4 w-4 text-lnd-accent" />
                                            Referral rate
                                        </span>
                                        <span className="font-Manrope text-xl font-bold text-lnd-fg">
                                            {referralRate.toFixed(1)}%
                                        </span>
                                    </div>
                                </div>

                                <div className="mt-6 rounded-xl border border-lnd-border bg-lnd-surface-2 p-4">
                                    <p className="text-[0.6rem] font-semibold uppercase tracking-[0.14em] text-lnd-fg-muted">
                                        Referral code
                                    </p>
                                    <div className="mt-2 flex items-center justify-between gap-2">
                                        <span className="font-mono text-sm font-semibold tracking-wide text-lnd-fg">
                                            {user.referral_code ?? "—"}
                                        </span>
                                        <button
                                            type="button"
                                            onClick={() =>
                                                copyToClipboard(
                                                    user.referral_code,
                                                )
                                            }
                                            aria-label="Copy referral code"
                                            className="rounded-full border border-lnd-border p-2 text-lnd-fg-muted transition-colors hover:border-lnd-accent/40 hover:text-lnd-accent"
                                        >
                                            <Copy className="h-3.5 w-3.5" />
                                        </button>
                                    </div>
                                </div>
                            </div>
                        </div>
                    </div>
                </div>
            </section>

            <ReferralSections />

            <PageCta
                eyebrow="Keep earning"
                title="Earn referral rewards now!"
                description="Every friend who registers with your link and trades earns you both rewards."
            />
        </div>
    );
}
